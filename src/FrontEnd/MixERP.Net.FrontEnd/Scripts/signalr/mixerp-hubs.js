/*
    Hub proxies formerly generated by ASP.NET SignalR 2 at /signalr/hubs, implemented on top of the
    ASP.NET Core SignalR client (Scripts/signalr/signalr.min.js, @microsoft/signalr 10.0.11, MIT license).

    The existing page scripts keep their API:
        $.connection.<hub>.client.<method> = function (...) { };
        $.connection.hub.start().done(function () { $.connection.<hub>.server.<method>(...); });

    Every hub is served by the application at /signalr/<hubName>.
*/
(function ($, signalR) {
    "use strict";

    if (!$ || !signalR) {
        return;
    }

    var hubNames = ["baseHub", "updateHub", "dayOperationHub", "dbHub"];
    var hubs = [];
    var root = $.connection || {};

    function toServerMethodName(name) {
        return name.charAt(0).toUpperCase() + name.slice(1);
    }

    function registerClientMethods(hub) {
        Object.keys(hub.client).forEach(function (method) {
            if (hub.registered[method]) {
                return;
            }

            hub.registered[method] = true;

            hub.connection.on(method, function () {
                var handler = hub.client[method];

                if (typeof handler === "function") {
                    handler.apply(hub.client, arguments);
                }
            });
        });
    }

    function ensureStarted(hub) {
        registerClientMethods(hub);

        if (hub.connection.state === signalR.HubConnectionState.Disconnected) {
            hub.starting = hub.connection.start();
        }

        return hub.starting || Promise.resolve();
    }

    function createHub(name) {
        var hub = {
            name: name,
            client: {},
            registered: {},
            starting: null,
            connection: new signalR.HubConnectionBuilder()
                .withUrl("/signalr/" + name)
                .withAutomaticReconnect()
                .build()
        };

        hub.server = new Proxy({}, {
            get: function (target, method) {
                return function () {
                    var args = Array.prototype.slice.call(arguments);
                    var deferred = $.Deferred();

                    ensureStarted(hub).then(function () {
                        return hub.connection.invoke.apply(hub.connection, [toServerMethodName(String(method))].concat(args));
                    }).then(deferred.resolve, deferred.reject);

                    return deferred.promise();
                };
            }
        });

        return hub;
    }

    hubNames.forEach(function (name) {
        var hub = createHub(name);
        hubs.push(hub);
        root[name] = hub;
    });

    root.hub = {
        start: function () {
            var deferred = $.Deferred();

            //Hubs without client callbacks are started on their first server call.
            var starting = hubs.filter(function (hub) {
                return Object.keys(hub.client).length > 0;
            }).map(ensureStarted);

            Promise.all(starting).then(function () {
                deferred.resolve();
            }, function (error) {
                deferred.reject(error);
            });

            return deferred.promise();
        }
    };

    $.connection = root;
})(window.jQuery, window.signalR);
