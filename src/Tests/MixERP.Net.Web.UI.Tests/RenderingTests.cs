using System;
using System.Data;
using System.Globalization;
using System.IO;
using MixERP.Net.Web.UI;
using MixERP.Net.Web.UI.HtmlControls;
using MixERP.Net.Web.UI.WebControls;
using Xunit;

namespace MixERP.Net.Web.UI.Tests
{
    public class RenderingTests
    {
        private static string Render(Control control)
        {
            using (StringWriter buffer = new StringWriter(CultureInfo.InvariantCulture))
            {
                using (HtmlTextWriter writer = new HtmlTextWriter(buffer))
                {
                    control.RenderControl(writer);
                }

                return buffer.ToString();
            }
        }

        [Fact]
        public void HtmlGenericControlRendersAttributesAndChildren()
        {
            HtmlGenericControl div = new HtmlGenericControl("div") {ID = "container"};
            div.Attributes.Add("class", "ui form");
            div.Style["display"] = "none";
            div.Controls.Add(new LiteralControl("<b>bold</b>"));

            Assert.Equal("<div id=\"container\" class=\"ui form\" style=\"display:none;\"><b>bold</b></div>", Render(div));
        }

        [Fact]
        public void InnerTextIsEncodedAndInnerHtmlIsNot()
        {
            HtmlGenericControl span = new HtmlGenericControl("span") {InnerText = "<a & b>"};
            HtmlGenericControl raw = new HtmlGenericControl("span") {InnerHtml = "<i>x</i>"};

            Assert.Equal("<span>&lt;a &amp; b&gt;</span>", Render(span));
            Assert.Equal("<span><i>x</i></span>", Render(raw));
        }

        [Fact]
        public void InvisibleControlsAreNotRendered()
        {
            Panel panel = new Panel {Visible = false};
            panel.Controls.Add(new LiteralControl("hidden"));

            Assert.Equal(string.Empty, Render(panel));
        }

        [Fact]
        public void InputControlsRenderNameAndValue()
        {
            HtmlInputText input = new HtmlInputText {ID = "Amount", Value = "10"};
            TextBox textBox = new TextBox {ID = "Name", Text = "a\"b", CssClass = "date"};
            HiddenField hidden = new HiddenField {ID = "UserIdHidden", Value = "1"};

            Assert.Equal("<input name=\"Amount\" id=\"Amount\" type=\"text\" value=\"10\" />", Render(input));
            Assert.Equal("<input name=\"Name\" type=\"text\" value=\"a&quot;b\" id=\"Name\" class=\"date\" />", Render(textBox));
            Assert.Equal("<input type=\"hidden\" name=\"UserIdHidden\" id=\"UserIdHidden\" value=\"1\" />", Render(hidden));
        }

        [Fact]
        public void DropDownListRendersSelectedOption()
        {
            DropDownList list = new DropDownList {ID = "Currency"};
            list.Items.Add(new ListItem("Dollar", "USD"));
            list.Items.Add(new ListItem("Euro", "EUR"));
            list.SelectedValue = "EUR";

            Assert.Equal("<select name=\"Currency\" id=\"Currency\"><option value=\"USD\">Dollar</option><option value=\"EUR\" selected=\"selected\">Euro</option></select>",
                Render(list));
        }

        [Fact]
        public void GridViewBindsDataTableAndRaisesRowDataBound()
        {
            DataTable table = new DataTable {Locale = CultureInfo.InvariantCulture};
            table.Columns.Add("item_name", typeof(string));
            table.Columns.Add("total", typeof(decimal));
            table.Rows.Add("Pen", 10.5m);
            table.Rows.Add("<Book>", 20m);

            GridView grid = new GridView {ID = "SalesGridView", AutoGenerateColumns = false, GridLines = GridLines.None, CssClass = "ui table"};
            grid.Columns.Add(new BoundField {HeaderText = "Item", DataField = "item_name"});
            grid.Columns.Add(new BoundField {HeaderText = "Total", DataField = "total", DataFormatString = "{0:N2}"});

            int dataRows = 0;
            grid.RowDataBound += (sender, e) =>
            {
                if (e.Row.RowType == DataControlRowType.DataRow)
                {
                    dataRows++;
                }
            };

            grid.DataSource = table;
            grid.DataBind();
            grid.HeaderRow.TableSection = TableRowSection.TableHeader;

            string html = Render(grid);

            Assert.Equal(2, dataRows);
            Assert.Equal(2, grid.Rows.Count);
            Assert.StartsWith("<div><table id=\"SalesGridView\" cellspacing=\"0\" class=\"ui table\" style=\"border-collapse:collapse;\"><thead><tr><th scope=\"col\">Item</th>", html);
            Assert.Contains("<td>&lt;Book&gt;</td>", html);
            Assert.Contains("<td>10.50</td>", html);
            Assert.EndsWith("</tbody></table></div>", html);
        }

        [Fact]
        public void AutoGeneratedColumnsExposeTheColumnDataType()
        {
            DataTable table = new DataTable {Locale = CultureInfo.InvariantCulture};
            table.Columns.Add("amount", typeof(decimal));
            table.Rows.Add(1m);

            GridView grid = new GridView();
            Type seen = null;
            grid.RowDataBound += (sender, e) =>
            {
                if (e.Row.RowType == DataControlRowType.Header)
                {
                    seen = ((AutoGeneratedField)((DataControlFieldCell)e.Row.Cells[0]).ContainingField).DataType;
                }
            };

            grid.DataSource = table;
            grid.DataBind();

            Assert.Equal(typeof(decimal), seen);
        }

        [Fact]
        public void FindControlDoesNotSearchInsideNestedNamingContainers()
        {
            PlaceHolder root = new PlaceHolder();
            Panel panel = new Panel();
            panel.Controls.Add(new Literal {ID = "Visible"});
            root.Controls.Add(panel);

            NamingProbe container = new NamingProbe {ID = "Container"};
            container.Controls.Add(new Literal {ID = "Hidden"});
            root.Controls.Add(container);

            Assert.NotNull(root.FindControl("Visible"));
            Assert.NotNull(root.FindControl("Container"));
            Assert.Null(root.FindControl("Hidden"));
            Assert.NotNull(container.FindControl("Hidden"));
        }

        [Fact]
        public void HeadUsesTheLiteralTitleOfTheMarkupAsPageTitle()
        {
            HtmlHead withTitle = new HtmlHead {Title = "Sign In & Go"};
            withTitle.Controls.Add(new LiteralControl("<meta charset=\"utf-8\" /><title>MixERP</title>"));

            HtmlHead withoutTitle = new HtmlHead();
            withoutTitle.Controls.Add(new LiteralControl("<title>MixERP</title>"));

            Assert.Equal("<head><meta charset=\"utf-8\" /><title>Sign In &amp; Go</title></head>", Render(withTitle));
            Assert.Equal("<head><title>MixERP</title></head>", Render(withoutTitle));
        }

        [Fact]
        public void UnsetUnitsAreNotRendered()
        {
            Panel panel = new Panel {ID = "Panel1"};
            Assert.True(panel.Width.IsEmpty);
            Assert.Equal("<div id=\"Panel1\"></div>", Render(panel));

            panel.Width = Unit.Percentage(100);
            Assert.Equal("<div id=\"Panel1\" style=\"width:100%;\"></div>", Render(panel));
        }

        [Fact]
        public void HtmlTextWriterQueuesAttributesForTheNextTag()
        {
            using (StringWriter buffer = new StringWriter(CultureInfo.InvariantCulture))
            {
                using (HtmlTextWriter writer = new HtmlTextWriter(buffer))
                {
                    writer.AddAttribute(HtmlTextWriterAttribute.Id, "reportheader");
                    writer.AddStyleAttribute(HtmlTextWriterStyle.TextAlign, "right");
                    writer.RenderBeginTag(HtmlTextWriterTag.Div);
                    writer.RenderBeginTag(HtmlTextWriterTag.Br);
                    writer.RenderEndTag();
                    writer.Write("text");
                    writer.RenderEndTag();
                }

                Assert.Equal("<div id=\"reportheader\" style=\"text-align:right;\"><br />text</div>", buffer.ToString());
            }
        }

        private sealed class NamingProbe : Control, INamingContainer
        {
        }
    }
}
