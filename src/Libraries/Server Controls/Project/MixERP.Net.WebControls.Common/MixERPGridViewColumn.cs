using Microsoft.AspNetCore.Components;
using System;

namespace MixERP.Net.WebControls.Common
{
    ////////////////////////////////////////////////////////////////////////////////////////////////////
    /// <summary>
    ///     One column of <see cref="MixERPGridView" />.
    ///     <para>
    ///         This replaces two removed WebForms types at once:
    ///         <c>System.Web.UI.WebControls.AutoGeneratedField</c> — which carried the
    ///         <c>DataType</c>, <c>HtmlEncode</c> and <c>HeaderStyle.CssClass</c> that
    ///         <c>MixERPGridView.OnRowDataBound</c> keyed all of its formatting off — and the
    ///         <c>DataControlField</c>/<c>TemplateField</c> entries the consumers that set
    ///         <c>AutoGenerateColumns = false</c> added to <c>GridView.Columns</c>
    ///         (TrialBalance, TransactionViewFactory, ScrudFactory). Auto-generated columns are
    ///         built from the data source by the component itself; explicitly declared ones are
    ///         passed in through <see cref="MixERPGridView.Columns" />.
    ///     </para>
    /// </summary>
    ////////////////////////////////////////////////////////////////////////////////////////////////////
    public sealed class MixERPGridViewColumn
    {
        public MixERPGridViewColumn()
        {
        }

        public MixERPGridViewColumn(string dataField, string headerText, Type dataType)
        {
            this.DataField = dataField;
            this.HeaderText = headerText;
            this.DataType = dataType;
        }

        /// <summary>The data-source column or property this cell reads.</summary>
        public string DataField { get; set; }

        /// <summary>The header caption. Auto-generated columns use the data field name, as a GridView did.</summary>
        public string HeaderText { get; set; }

        /// <summary>
        ///     The CLR type of the column's values — the former <c>AutoGeneratedField.DataType</c>,
        ///     which selects the number/date formatting in
        ///     <c>MixERPGridView.FormatCellValue</c>.
        /// </summary>
        public Type DataType { get; set; }

        /// <summary>
        ///     Overrides the computed data-cell css class. Leave null to keep the ported
        ///     behaviour ("text right" for Decimal/Double/Single, none otherwise).
        /// </summary>
        public string CssClass { get; set; }

        /// <summary>
        ///     Overrides the computed header css class. Leave null to keep the ported
        ///     behaviour ("text right" for Decimal/Double/Single, "text left" otherwise).
        /// </summary>
        public string HeaderCssClass { get; set; }

        /// <summary>
        ///     Optional per-row cell template, the replacement for the
        ///     <c>TemplateField</c>s the explicit-column consumers added (for example
        ///     ScrudFactory's select-checkbox column). When set it renders instead of the
        ///     formatted value.
        /// </summary>
        public RenderFragment<object> Template { get; set; }
    }
}
